<?php

namespace App\Modules\Hrm\database\seeders;

use App\Modules\Foundation\Models\Business;
use Illuminate\Database\Seeder;
use Spatie\Permission\Models\Permission;
use Spatie\Permission\Models\Role;

/**
 * HRM permissions. Seeded to Owner; HR-specific roles (HR Admin, HR Manager,
 * …) created through the Roles UI can be granted these without a code change.
 */
class HrmPermissionsSeeder extends Seeder
{
    private const ROLE_PERMISSIONS = [
        'Owner' => [
            'hrm.employees.manage',
            'hrm.scheduling.manage',
            'hrm.attendance.manage',
            'hrm.attendance.approve',
            'hrm.leave.manage',
            'hrm.leave.approve',
            // Correction C5 / ACL-02: salary is visible to the employee
            // themselves, Payroll HR, Finance and authorised Management —
            // explicitly NOT to Department Managers. `manage` sets structures,
            // `view` is read-only for Finance and Management.
            'hrm.salary.manage',
            'hrm.salary.view',
            // WFL-04: payroll is generated by a Payroll Officer or HR Admin.
            'hrm.payroll.manage',
        ],
        // COR-03's first correction stage. Held separately from
        // hrm.attendance.manage so a Manager can approve their team's
        // corrections without gaining HR's full attendance administration.
        'Manager' => [
            'hrm.attendance.approve',
            // LEV-05's first stage and POL-10's manager confirmation.
            'hrm.leave.approve',
            // Note: a Manager deliberately gets NO salary permission.
            // Correction C5 (ACL-02) excludes Department Managers from seeing
            // their team's salary amounts.
        ],
        // Seeded by HrmChangeRequestWorkflowSeeder for the bank-change stage;
        // C5 also grants Finance read access to salary.
        'Finance' => [
            'hrm.salary.view',
        ],
    ];

    public function run(): void
    {
        $permissionNames = collect(self::ROLE_PERMISSIONS)->flatten()->unique();

        foreach ($permissionNames as $name) {
            Permission::firstOrCreate(['name' => $name, 'guard_name' => 'web']);
        }

        foreach (Business::all() as $business) {
            foreach (self::ROLE_PERMISSIONS as $roleName => $permissions) {
                $role = Role::where('business_id', $business->id)->where('name', $roleName)->first();

                if ($role) {
                    $role->givePermissionTo($permissions);
                }
            }
        }
    }
}
